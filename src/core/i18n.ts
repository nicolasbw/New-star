const DICTS: Record<Lang, Dict> = { pt, en };

let lang: Lang = 'pt';
try {
  const saved = localStorage.getItem('newstar.lang');
  if (saved === 'pt' || saved === 'en') lang = saved;
  else if (typeof navigator !== 'undefined' && !navigator.language.toLowerCase().startsWith('pt')) lang = 'en';
} catch {
  /* ignore */
}

export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem('newstar.lang', l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l === 'pt' ? 'pt-BR' : 'en';
}

export function t(key: string, p?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.pt[key] ?? key;
  if (p) {
    for (const k of Object.keys(p)) {
      let v = p[k];
      // values that are themselves keys get translated
      if (typeof v === 'string' && (DICTS[lang][v] !== undefined)) v = DICTS[lang][v];
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

